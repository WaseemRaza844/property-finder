"""Generate the browser catalog from the same market configuration as ingestion."""
import json
from pathlib import Path


def catalog(root):
    config = json.loads((root / 'config/searches.json').read_text(encoding='utf-8'))
    return {m['id']: {**m, 'nearby': m['towns'][1:], 'city': m['towns'][0].rsplit(' ', 1)[0] + ', ' + m['towns'][0].rsplit(' ', 1)[1]} for m in config['markets']}


def sync(root):
    content = '// Generated by scripts/sync_markets.py from config/searches.json.\nexport const markets = ' + json.dumps(catalog(root), ensure_ascii=False, indent=2) + ';\n'
    (root / 'web/markets.js').write_text(content, encoding='utf-8')


if __name__ == '__main__':
    sync(Path(__file__).resolve().parents[1])
